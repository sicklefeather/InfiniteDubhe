using InfiniteDubhe.Core;
using InfiniteDubhe.Rendering;

namespace InfiniteDubhe.UI;

/// <summary>
/// 内置 5×7 位图字体：把内置字形数据渲染为一张 GPU 图集，供 <see cref="Text"/> 采样。
/// 覆盖 ASCII 32–126（95 个可打印字符），等宽推进；不支持的字形返回空矩形。
/// </summary>
public sealed class BitmapFont
{
    public const int GlyphWidth = 5;
    public const int GlyphHeight = 7;
    public const int CellWidth = 6;    // 字形宽 + 1px 间距
    public const int CellHeight = 8;   // 字形高 + 1px 间距
    public const int Columns = 16;
    public const int Rows = 6;

    /// <summary>图集纹理。</summary>
    public ITexture Texture { get; }

    /// <summary>等宽推进宽度（像素）。</summary>
    public int Advance => CellWidth;

    private BitmapFont(ITexture texture) => Texture = texture;

    /// <summary>返回字符 <paramref name="c"/> 在图集中的源矩形（不支持则 <see cref="Rectangle.Empty"/>）。</summary>
    public Rectangle GetGlyph(char c)
    {
        int index = c - ' ';
        if (index < 0 || index >= Columns * Rows) return Rectangle.Empty;
        int col = index % Columns;
        int row = index / Columns;
        return new Rectangle(col * CellWidth, row * CellHeight, GlyphWidth, GlyphHeight);
    }

    /// <summary>把内置字形渲染成图集纹理。</summary>
    public static BitmapFont Build(Renderer renderer)
    {
        ArgumentNullException.ThrowIfNull(renderer);

        var glyphs = GlyphTable;
        int width = Columns * CellWidth;
        int height = Rows * CellHeight;
        var rgba = new byte[width * height * 4];

        for (int i = 0; i < glyphs.Length; i++)
        {
            string glyph = glyphs[i];
            int col = i % Columns;
            int row = i / Columns;
            for (int gy = 0; gy < GlyphHeight; gy++)
            {
                for (int gx = 0; gx < GlyphWidth; gx++)
                {
                    if (glyph[gy * GlyphWidth + gx] != '#') continue;
                    int px = col * CellWidth + gx;
                    int py = row * CellHeight + gy;
                    int o = (py * width + px) * 4;
                    rgba[o] = rgba[o + 1] = rgba[o + 2] = rgba[o + 3] = 255;
                }
            }
        }

        return new BitmapFont(renderer.CreateTexture(width, height, rgba));
    }

    private static readonly string[] GlyphTable = BuildGlyphTable();

    private static string[] BuildGlyphTable()
    {
        var lines = FontData.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
        var glyphs = new List<string>(95);
        var current = new List<string>(7);

        foreach (var line in lines)
        {
            if (line.Length == 0)
            {
                if (current.Count == 7)
                {
                    glyphs.Add(string.Concat(current));
                    current.Clear();
                }
                continue;
            }
            current.Add(line);
        }
        if (current.Count == 7) glyphs.Add(string.Concat(current));

        if (glyphs.Count != 95)
            throw new InvalidOperationException($"内置字体数据损坏：期望 95 个字形，实际 {glyphs.Count} 个。");
        return glyphs.ToArray();
    }

